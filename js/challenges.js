/* Strict syntax check: unclosed quotes, brackets, Python-2 print, lines stopping mid-expression */
function pyStrict(code){
 const lines=code.split('\n'),st=[],pair={')':'(',']':'[','}':'{'},nm={'(':'parenthesis','[':'bracket','{':'brace'},close={'(':')','[':']','{':'}'};let tq='',tl=0;
 for(let n=0;n<lines.length;n++){const L=lines[n];let i=0;
  while(i<L.length){const c=L[i];
   if(tq){const j=L.indexOf(tq,i);if(j<0){i=L.length;break}i=j+3;tq='';continue}
   if(c==='#')break;
   if(c==='"'||c==="'"){if(L.startsWith(c.repeat(3),i)){tq=c.repeat(3);tl=n+1;i+=3;continue}
    let j=i+1;while(j<L.length&&L[j]!==c){if(L[j]==='\\')j++;j++}
    if(j>=L.length)return'SyntaxError: unterminated string literal (detected at line '+(n+1)+'). The quote mark ('+c+') is never closed - add the closing '+c+'.';
    i=j+1;continue}
   if('([{'.includes(c))st.push({c,n:n+1});
   else if(')]}'.includes(c)){const o=st.pop();if(!o)return'SyntaxError: unmatched \''+c+'\' on line '+(n+1)+' (nothing to close).';
    if(o.c!==pair[c])return'SyntaxError: closing '+nm[pair[c]]+' \''+c+'\' on line '+(n+1)+' does not match the opening '+nm[o.c]+' \''+o.c+'\' on line '+o.n+'.'}
   i++}}
 if(tq)return'SyntaxError: unterminated triple-quoted string literal (started on line '+tl+').';
 if(st.length){const o=st[st.length-1];return'SyntaxError: \''+o.c+'\' on line '+o.n+' was never closed - add closing \''+close[o.c]+'\'.'}
 const S=PyIndent.scan(code).lines;
 for(let i=0;i<S.length;i++){const l=S[i];if(l.cont||!l.code)continue;let e=i;while(e+1<S.length&&S[e+1].cont)e++;const end=S[e].code||l.code;
  if(/^print\s+[^\s(=]/.test(l.code))return'SyntaxError: line '+(i+1)+': Missing parentheses in call to \'print\'. Write print(...) with brackets.';
  if(/(^|[^=!<>+\-*\/%])=\s*$|[+\-*\/%<>]\s*$|\b(and|or|not|in|is)\s*$/.test(end)&&!/:$/.test(end))return'SyntaxError: invalid syntax on line '+(i+1)+' - the statement stops in the middle of an expression.'}
 return'';
}

